-- Aula 15: usuários que podem entrar no sistema.
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    -- O e-mail é o "login". UNIQUE: o banco recusa dois usuários com o mesmo
    -- e-mail, mesmo que duas requisições cheguem ao mesmo tempo.
    email VARCHAR(255) NOT NULL UNIQUE,
    -- NUNCA a senha: só o HASH BCrypt dela (sempre 60 caracteres, começa com $2a$).
    senha_hash VARCHAR(60) NOT NULL,

    -- Segundo fator (TOTP, o código de 6 dígitos do aplicativo autenticador).
    -- O segredo é gerado no "configurar" e só passa a valer depois do "ativar".
    totp_segredo VARCHAR(64),
    totp_ativo BOOLEAN NOT NULL DEFAULT FALSE,
    -- O último "passo" de 30 segundos já usado: o mesmo código não entra duas vezes.
    totp_ultimo_passo BIGINT NOT NULL DEFAULT 0,

    -- Proteção contra força bruta: erros seguidos e até quando a conta fica bloqueada.
    tentativas_falhas INT NOT NULL DEFAULT 0,
    bloqueado_ate TIMESTAMP WITH TIME ZONE,

    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
